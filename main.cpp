#include <bits/stdc++.h>
#include "Model/RubiksCube1dArray.cpp"
#include "Model/RubiksCube3dArray.cpp"
#include "Model/RubiksCubeBitboard.cpp"
#include "Solver/DFSSolver.h"
#include "Solver/BFSSolver.h"
#include "Solver/IDDFSSolver.h"
#include "Solver/IDAstarSolver.h"
#include "PatternDatabases/CornerDBMaker.h"

using namespace std;

/*
 * Command-line driver.
 *
 *   rubiks_cube_solver [--solver ida|iddfs|bfs|dfs] [--scramble N] [--db PATH]
 *
 * --solver   which search algorithm to run (default: ida)
 * --scramble number of random moves used to scramble the cube (default: 8)
 * --db       path to the corner pattern database used by IDA*
 *            (default: Databases/cornerDepth8.bin). It is generated by BFS
 *            the first time if the file does not exist yet.
 */

static void printUsage(const char *prog) {
    cout << "Usage: " << prog << " [--solver ida|iddfs|bfs|dfs] [--scramble N] [--db PATH]\n";
}

static string movesToString(const vector<RubiksCube::MOVE> &moves) {
    string out;
    for (auto m: moves) out += RubiksCube::getMove(m) + " ";
    return out;
}

int main(int argc, char **argv) {
    string solverName = "ida";
    unsigned scrambleLen = 8;
    string dbPath = "Databases/cornerDepth8.bin";

    for (int i = 1; i < argc; i++) {
        string arg = argv[i];
        if (arg == "--solver" && i + 1 < argc) solverName = argv[++i];
        else if (arg == "--scramble" && i + 1 < argc) scrambleLen = stoi(argv[++i]);
        else if (arg == "--db" && i + 1 < argc) dbPath = argv[++i];
        else {
            printUsage(argv[0]);
            return arg == "--help" || arg == "-h" ? 0 : 1;
        }
    }

    // The bitboard model is the fastest of the three representations, so every
    // solver runs on it here. The 1D and 3D models implement the same interface.
    RubiksCubeBitboard cube;
    vector<RubiksCube::MOVE> scramble = cube.randomShuffleCube(scrambleLen);

    cout << "Scramble (" << scramble.size() << " moves): " << movesToString(scramble) << "\n";
    cube.print();

    vector<RubiksCube::MOVE> solution;
    auto start = chrono::steady_clock::now();

    try {
        if (solverName == "ida") {
            if (!ifstream(dbPath).good()) {
                cout << "Pattern database not found at " << dbPath
                     << ", generating it with BFS (one-time, can take a few minutes)...\n";
                filesystem::path parent = filesystem::path(dbPath).parent_path();
                if (!parent.empty()) filesystem::create_directories(parent);
                CornerDBMaker dbMaker(dbPath);
                dbMaker.bfsAndStore();
                cout << "Database written.\n";
                start = chrono::steady_clock::now();
            }
            IDAstarSolver<RubiksCubeBitboard, HashBitboard> solver(cube, dbPath);
            solution = solver.solve();
        } else if (solverName == "iddfs") {
            IDDFSSolver<RubiksCubeBitboard, HashBitboard> solver(cube, 7);
            solution = solver.solve();
        } else if (solverName == "bfs") {
            BFSSolver<RubiksCubeBitboard, HashBitboard> solver(cube);
            solution = solver.solve();
        } else if (solverName == "dfs") {
            DFSSolver<RubiksCubeBitboard, HashBitboard> solver(cube, 8);
            solution = solver.solve();
        } else {
            printUsage(argv[0]);
            return 1;
        }
    } catch (const exception &e) {
        cerr << "Error: " << e.what() << "\n";
        return 1;
    }

    double secs = chrono::duration<double>(chrono::steady_clock::now() - start).count();

    // Independently verify the answer by replaying it on the scrambled cube.
    RubiksCubeBitboard check = cube;
    for (auto m: solution) check.move(m);

    cout << "Solver: " << solverName << "\n";
    cout << "Solution (" << solution.size() << " moves): " << movesToString(solution) << "\n";
    cout << "Time: " << fixed << setprecision(3) << secs << " s\n";
    cout << (check.isSolved() ? "Verified: cube is solved.\n" : "WARNING: solution does not solve the cube.\n");
    return check.isSolved() ? 0 : 2;
}
